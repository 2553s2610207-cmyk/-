import streamlit as st

# 1. 앱 제목 설정 (도서관 간판 달기)
st.title("📚 나만의 미니 책 추천 사서")
st.write("원하는 장르를 선택하면 책을 추천해줄게!")

# 2. 데이터베이스 구축 (책장 정리하기)
# 실제 서비스라면 DB나 CSV를 쓰겠지만, 가장 간단하게 딕셔너리로 만들었긔!
book_data = {
    "소설": ["불편한 편의점 (김호연)", "메리골드 마음 세탁소 (윤정은)", "구의 증명 (최진영)"],
    "에세이/시": ["운다고 달라지는 일은 아무것도 없겠지만 (박준)", "물고기는 존재하지 않는다 (룰루 밀러)", "나태주 시선집 (나태주)"],
    "역사": ["거꾸로 읽는 세계사 (유시민)", "역사의 쓸모 (최태성)", "사피엔스 (유발 하라리)"],
    "과학": ["코스모스 (칼 세이건)", "물질의 세계 (김병민)", "과학이 필요한 시간 (인하대 교수진)"]
}

# 3. 사용자 입력 받기 (손님에게 장르 물어보기)
# 사이드바나 메인 화면에 드롭다운 메뉴를 만드는 기능이긔
selected_genre = st.selectbox("어떤 장르의 책을 읽고 싶어?", list(book_data.keys()))

# 4. 결과 출력하기 (추천 도서 보여주기)
st.divider() # 깔끔하게 줄 하나 그어주고!
st.subheader(f"🔍 '{selected_genre}' 장르 추천 도서")

# 선택한 장르에 있는 책들을 하나씩 꺼내서 리스트로 보여주는 코드야
for book in book_data[selected_genre]:
    st.write(f"- {book}")

